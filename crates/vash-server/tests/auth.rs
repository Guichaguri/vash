/// The whole opcode space, not a list someone maintained by hand: an opcode
/// added later without a gate has to fail here rather than ship.
#[tokio::test]
async fn no_vcp_opcode_executes_unauthenticated() {
    let (server, _) = TestServer::start().await;

    // The two that are legal before authenticating, each for a stated reason:
    // HELLO because the dialect must be announced first, AUTH because it is the
    // thing being announced.
    let pre_auth = [Opcode::Hello as u8, Opcode::Auth as u8];

    for byte in 0u8..=255 {
        if pre_auth.contains(&byte) {
            continue;
        }

        let mut conn = server.connect().await;
        conn.hello().await;
        let (status, body) = conn.raw_vcp(byte, b"whatever-body-this-opcode-wants").await;

        // Unknown and unimplemented opcodes included: answering `UNSUPPORTED`
        // to those would let an unauthenticated party enumerate which opcodes
        // this build has.
        assert_eq!(
            status,
            Status::Unauthorized,
            "opcode {byte:#04x} ({:?}) answered {status:?} unauthenticated",
            Opcode::from_u8(byte)
        );
        assert!(body.is_empty(), "opcode {byte:#04x} leaked a refusal body");
    }
}

