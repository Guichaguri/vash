/// Redis distinguishes "your credential is wrong" from "there is nothing here
/// to authenticate against", and a client must never have the two confused.
#[tokio::test]
async fn redis_says_so_when_no_credential_is_configured() {
    let dir = tempfile::tempdir().unwrap();
    let mut config = Config::default();
    config.server.listen = "127.0.0.1:0".parse().unwrap();
    config.store.path = dir.path().join("db");
    config.store.map_size_mb = 64;
    config.observability.admin_listen = "127.0.0.1:0".into();

    let server = Server::bind(config).await.unwrap();
    let addr = server.local_addr().unwrap();
    let (tx, rx) = oneshot::channel::<()>();
    let handle = tokio::spawn(async move {
        server
            .serve(async {
                let _ = rx.await;
            })
            .await
    });

    let stream = TcpStream::connect(addr).await.unwrap();
    let mut conn = Conn {
        stream,
        buf: Vec::new(),
    };
    conn.send(&resp(&["AUTH", "anything"])).await;
    assert_eq!(
        conn.read_until("\r\n").await,
        "-ERR AUTH <password> called without any password configured for the default user. \
         Are you sure your configuration is correct?\r\n"
    );

    drop(tx);
    let _ = handle.await;
}

