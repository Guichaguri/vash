/// The foot-gun this whole feature is most likely to trip: peers are ordinary
/// VCP clients on the ordinary port, so auth without a peer credential breaks
/// invalidation cluster-wide *while every node reports itself healthy*.
/// Refusing to start is the only failure mode an operator cannot miss.
#[test]
fn a_clustered_node_without_a_peer_credential_refuses_to_start() {
    let mut config = Config::default();
    config.auth.required = true;
    config.auth.file = PathBuf::from("/nonexistent/credentials");
    config.cluster.peers = vec!["127.0.0.1:11312".into()];

    let error = format!("{:#}", config.validate().unwrap_err());
    assert!(error.contains("cluster.auth_secret"), "{error}");

    config.cluster.auth_secret = "a-secret-long-enough".into();
    assert!(config.validate().is_ok());
}

/// Enforcement with an empty table locks out every client including the node's
/// own peers.
#[tokio::test]
async fn enforcement_without_credentials_refuses_to_start() {
    let dir = tempfile::tempdir().unwrap();
    let mut config = Config::default();
    config.server.listen = "127.0.0.1:0".parse().unwrap();
    config.store.path = dir.path().join("db");
    config.store.map_size_mb = 64;
    config.observability.admin_listen = "127.0.0.1:0".into();
    config.auth.required = true;

    let Err(error) = Server::bind(config).await else {
        panic!("a server with auth required and no credentials must not start");
    };
    let error = format!("{error:#}");
    assert!(error.contains("no credentials are configured"), "{error}");
}
