/// `HELLO` has to work before `AUTH` — first-byte detection requires a VCP
/// connection to open with it, so there is no way to authenticate first. The
/// capability bit is how a client discovers that it must.
#[tokio::test]
async fn hello_is_answered_before_auth_and_advertises_the_requirement() {
    let (server, _) = TestServer::start().await;
    let mut conn = server.connect().await;

    let capabilities = conn.hello().await;
    assert_ne!(
        capabilities & vash_core::capability::AUTH_REQUIRED,
        0,
        "a server that requires auth must say so in HELLO"
    );
}

