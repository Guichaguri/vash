//! Authentication, over a real socket, in all three dialects.
//!
//! The test that matters most is [`no_vcp_opcode_executes_unauthenticated`]:
//! it enumerates the whole opcode space rather than the opcodes someone
//! remembered to list, so an opcode added later without a gate fails here
//! instead of shipping.

use std::net::SocketAddr;
use std::path::{Path, PathBuf};

use tempfile::TempDir;
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::TcpStream;
use tokio::sync::oneshot;
use tokio::task::JoinHandle;
use vash_proto::vcp::{HEADER_LEN, Opcode, Status, encode_auth_body, encode_request};
use vash_server::{Config, Server};

const NAME: &str = "billing-api";

struct TestServer {
    addr: SocketAddr,
    _dir: TempDir,
    shutdown: Option<oneshot::Sender<()>>,
    handle: Option<JoinHandle<anyhow::Result<()>>>,
}

impl TestServer {
    /// Starts a server with one credential, enforced.
    async fn start() -> (Self, String) {
        Self::start_with(true, |_| {}).await
    }

    async fn start_with(required: bool, tweak: impl FnOnce(&mut Config)) -> (Self, String) {
        let dir = tempfile::tempdir().unwrap();
        let (secret, line) = vash_server::auth::generate(NAME).unwrap();
        let credentials = write_credentials(dir.path(), &line);

        let mut config = Config::default();
        config.server.listen = "127.0.0.1:0".parse().unwrap();
        config.store.path = dir.path().join("db");
        // The whole protocol suite runs against whichever engine this build
        // carries, so `--features mdbx` re-runs it on the second one. See
        // `crates/vash-store/tests/store.rs` for the same arrangement a layer
        // down, and `docs/mdbx-proposal.md` for why the choice is per build.
        #[cfg(feature = "mdbx")]
        {
            config.store.backend = vash_server::config::Backend::Mdbx;
        }
        config.store.map_size_mb = 64;
        // One LMDB environment rather than one per shard. Nothing here is about
        // sharding, and the suite runs in parallel against a finite pool of
        // thread-local slots — past it, `MDB_TLS_FULL`.
        config.store.shards = 1;
        config.observability.admin_listen = "127.0.0.1:0".into();
        config.auth.required = required;
        config.auth.file = credentials;
        tweak(&mut config);

        let server = Server::bind(config).await.expect("binding");
        let addr = server.local_addr().unwrap();
        let (tx, rx) = oneshot::channel();
        let handle = tokio::spawn(async move {
            server
                .serve(async {
                    let _ = rx.await;
                })
                .await
        });

        (
            Self {
                addr,
                _dir: dir,
                shutdown: Some(tx),
                handle: Some(handle),
            },
            secret,
        )
    }

    async fn connect(&self) -> Conn {
        let stream = TcpStream::connect(self.addr).await.expect("connecting");
        stream.set_nodelay(true).unwrap();
        Conn {
            stream,
            buf: Vec::new(),
        }
    }
}

impl Drop for TestServer {
    fn drop(&mut self) {
        drop(self.shutdown.take());
        self.handle.take();
    }
}

/// Writes a credential file the loader will accept.
///
/// The mode matters on Unix: the loader refuses a group- or world-readable
/// credential file the way `ssh` refuses a loose private key, and a temp file
/// is 0644 by default — so without this the whole suite would fail on CI and
/// pass on a Windows dev box.
fn write_credentials(dir: &Path, line: &str) -> PathBuf {
    let path = dir.join("credentials");
    std::fs::write(&path, format!("# generated by the test suite\n{line}\n")).unwrap();

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o600)).unwrap();
    }

    path
}

struct Conn {
    stream: TcpStream,
    buf: Vec<u8>,
}

impl Conn {
    async fn send(&mut self, bytes: &[u8]) {
        self.stream.write_all(bytes).await.expect("writing");
    }

    /// Sends one VCP frame and returns `(status, body)`.
    async fn vcp(&mut self, opcode: Opcode, body: &[u8]) -> (Status, Vec<u8>) {
        self.raw_vcp(opcode as u8, body).await
    }

    /// The same, for an opcode byte the encoder has no enum variant for — which
    /// is how [`no_vcp_opcode_executes_unauthenticated`] covers the bytes this
    /// build does not implement.
    async fn raw_vcp(&mut self, opcode: u8, body: &[u8]) -> (Status, Vec<u8>) {
        let mut frame = Vec::new();
        encode_request(&mut frame, Opcode::Ping, 7, body);
        frame[0] = opcode;
        self.send(&frame).await;

        self.fill(HEADER_LEN).await;
        let status = Status::from_u16(u16::from_le_bytes([self.buf[2], self.buf[3]]))
            .expect("a status this build knows");
        let body_len = u32::from_le_bytes(self.buf[8..12].try_into().unwrap()) as usize;
        assert_eq!(
            u32::from_le_bytes(self.buf[4..8].try_into().unwrap()),
            7,
            "the request id must be echoed"
        );

        self.fill(HEADER_LEN + body_len).await;
        let payload = self.buf[HEADER_LEN..HEADER_LEN + body_len].to_vec();
        self.buf.drain(..HEADER_LEN + body_len);
        (status, payload)
    }

    async fn hello(&mut self) -> u32 {
        let mut body = Vec::new();
        body.extend_from_slice(&1u16.to_le_bytes());
        body.extend_from_slice(&0u16.to_le_bytes());
        let (status, payload) = self.vcp(Opcode::Hello, &body).await;
        assert_eq!(status, Status::Ok, "HELLO must work before AUTH");
        u32::from_le_bytes(payload[12..16].try_into().unwrap())
    }

    async fn auth(&mut self, mechanism: u8, name: &str, secret: &str) -> Status {
        let mut body = Vec::new();
        encode_auth_body(&mut body, mechanism, name.as_bytes(), secret.as_bytes());
        self.vcp(Opcode::Auth, &body).await.0
    }

    async fn fill(&mut self, wanted: usize) {
        let mut chunk = [0u8; 8192];
        let deadline = tokio::time::Instant::now() + std::time::Duration::from_secs(5);
        while self.buf.len() < wanted {
            let read = tokio::time::timeout_at(deadline, self.stream.read(&mut chunk))
                .await
                .unwrap_or_else(|_| panic!("timed out waiting for {wanted} bytes"))
                .expect("reading");
            assert_ne!(read, 0, "server closed while a reply was outstanding");
            self.buf.extend_from_slice(&chunk[..read]);
        }
    }

    /// Reads text until it ends with `terminator`, for the two text dialects.
    async fn read_until(&mut self, terminator: &str) -> String {
        let mut chunk = [0u8; 8192];
        let deadline = tokio::time::Instant::now() + std::time::Duration::from_secs(5);
        loop {
            if let Ok(text) = std::str::from_utf8(&self.buf)
                && text.ends_with(terminator)
            {
                let out = text.to_string();
                self.buf.clear();
                return out;
            }
            let read = tokio::time::timeout_at(deadline, self.stream.read(&mut chunk))
                .await
                .unwrap_or_else(|_| {
                    panic!(
                        "timed out waiting for {terminator:?}; have {:?}",
                        String::from_utf8_lossy(&self.buf)
                    )
                })
                .expect("reading");
            assert_ne!(read, 0, "server closed while waiting for {terminator:?}");
            self.buf.extend_from_slice(&chunk[..read]);
        }
    }

    async fn text(&mut self, command: &str) -> String {
        self.send(command.as_bytes()).await;
        self.read_until("\r\n").await
    }
}

/// Builds a RESP request array.
fn resp(args: &[&str]) -> Vec<u8> {
    let mut out = format!("*{}\r\n", args.len()).into_bytes();
    for arg in args {
        out.extend_from_slice(format!("${}\r\n", arg.len()).as_bytes());
        out.extend_from_slice(arg.as_bytes());
        out.extend_from_slice(b"\r\n");
    }
    out
}

