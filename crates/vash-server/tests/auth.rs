/// `NO_REPLY` suppresses a reply, and must not suppress the gate with it.
#[tokio::test]
async fn no_reply_cannot_smuggle_a_write_past_the_gate() {
    let (server, secret) = TestServer::start().await;
    let mut conn = server.connect().await;
    conn.hello().await;

    let mut set = Vec::new();
    vash_proto::vcp::encode_set_body(&mut set, b"smuggled", b"value", 0, &[]);
    let mut frame = Vec::new();
    encode_request(&mut frame, Opcode::Set, 1, &set);
    // Flip NO_REPLY on the built frame.
    frame[1] |= vash_proto::vcp::flags::NO_REPLY;
    conn.send(&frame).await;

    // Authenticate on the same connection, then look for the key. A gate that
    // only skipped the *reply* would have written it.
    assert_eq!(conn.auth(0, NAME, &secret).await, Status::Ok);
    assert_eq!(conn.vcp(Opcode::Get, b"smuggled").await.0, Status::NotFound);
}

/// An `AUTH` and the commands it authorises can arrive in a single read, so
/// authentication has to take effect within a block rather than between reads.
#[tokio::test]
async fn auth_takes_effect_inside_a_pipelined_block() {
    let (server, secret) = TestServer::start().await;
    let mut conn = server.connect().await;
    conn.hello().await;

    let mut batch = Vec::new();
    let mut auth_body = Vec::new();
    encode_auth_body(&mut auth_body, 0, NAME.as_bytes(), secret.as_bytes());
    encode_request(&mut batch, Opcode::Auth, 1, &auth_body);
    encode_request(&mut batch, Opcode::Ping, 2, &[]);
    conn.send(&batch).await;

    // The `AUTH` reply carries the granted roles, so the second frame does not
    // start at `HEADER_LEN` — its offset has to come from the first body length.
    conn.fill(HEADER_LEN).await;
    let first = Status::from_u16(u16::from_le_bytes([conn.buf[2], conn.buf[3]])).unwrap();
    let first_body = u32::from_le_bytes(conn.buf[8..12].try_into().unwrap()) as usize;
    let second_at = HEADER_LEN + first_body;

    conn.fill(second_at + HEADER_LEN).await;
    let second = Status::from_u16(u16::from_le_bytes([
        conn.buf[second_at + 2],
        conn.buf[second_at + 3],
    ]))
    .unwrap();

    assert_eq!(first, Status::Ok);
    assert_eq!(
        second,
        Status::Ok,
        "the PING in the same read must see the AUTH before it"
    );
}

/// A twelve-byte header claiming a 64 MiB body would otherwise make the server
/// reserve 64 MiB for a connection that has presented nothing.
#[tokio::test]
async fn an_unauthenticated_connection_cannot_make_the_server_reserve() {
    let (server, _) = TestServer::start().await;
    let mut conn = server.connect().await;
    conn.hello().await;

    // A header only: the body it promises never arrives.
    let mut frame = Vec::new();
    encode_request(&mut frame, Opcode::Set, 1, &[]);
    frame[8..12].copy_from_slice(&(32 * 1024 * 1024u32).to_le_bytes());
    conn.send(&frame).await;

    let mut chunk = [0u8; 64];
    let read = tokio::time::timeout(
        std::time::Duration::from_secs(5),
        conn.stream.read(&mut chunk),
    )
    .await
    .expect("the server should have closed rather than reserved")
    .expect("reading");
    assert_eq!(read, 0, "expected a clean close, not a reservation");
}

/// The same bound over a text dialect, where the length is not in a header:
/// bytes simply accumulate until something parses.
#[tokio::test]
async fn an_unauthenticated_text_connection_cannot_fill_the_buffer() {
    let (server, _) = TestServer::start().await;
    let mut conn = server.connect().await;

    // A `get` line that never terminates. Every byte is a legal command byte,
    // so only the pre-auth budget stops it.
    conn.send(b"get ").await;
    conn.send(&vec![b'k'; 8192]).await;

    let mut chunk = [0u8; 64];
    let read = tokio::time::timeout(
        std::time::Duration::from_secs(5),
        conn.stream.read(&mut chunk),
    )
    .await
    .expect("the server should have closed")
    .expect("reading");
    assert_eq!(read, 0);
}

#[tokio::test]
async fn too_many_failures_close_the_connection() {
    let (server, _) = TestServer::start_with(true, |config| config.auth.max_attempts = 2).await;
    let mut conn = server.connect().await;
    conn.hello().await;

    assert_eq!(conn.auth(0, NAME, "wrong").await, Status::Unauthorized);
    // The second failure is answered, and *then* the socket goes: the client
    // learns why rather than seeing a bare disconnect.
    assert_eq!(conn.auth(0, NAME, "wrong").await, Status::Unauthorized);

    let mut chunk = [0u8; 64];
    let read = tokio::time::timeout(
        std::time::Duration::from_secs(5),
        conn.stream.read(&mut chunk),
    )
    .await
    .expect("the server should have closed the connection")
    .expect("reading");
    assert_eq!(read, 0, "expected a clean close after the attempt cap");
}

